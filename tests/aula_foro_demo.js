const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { chromium } = require('playwright');

const datos = JSON.parse(fs.readFileSync(path.join(__dirname, '..', 'site', 'aula', 'data.js'), 'utf8').replace(/^window\.CURSO=/, '').replace(/;$/, ''));
datos.config.firebase = {};
const URL_AULA = 'http://localhost:8765/aula/index.html';

async function registrar(page, email, cedula, nombre) {
  await page.goto(URL_AULA + '#/registro');
  const campos = { nombres: nombre, apellidos: 'Prueba', cedula, fechaNac: '1995-03-14', sexo: 'Femenino', nacionalidad: 'Paraguaya', departamento: 'Central', ciudad: 'Luque', email, clave: 'Clave1234', clave2: 'Clave1234' };
  for (const [k, v] of Object.entries(campos)) {
    const el = page.locator('#f_' + k);
    if (await el.evaluate(e => e.tagName) === 'SELECT') await el.selectOption(v); else await el.fill(v);
  }
  await page.locator('#f_ok').check();
  await page.locator('#rg button[type=submit]').click();
  await page.waitForSelector('h1:has-text("Hola")');
}

(async () => {
  const browser = await chromium.launch();
  const context = await browser.newContext({ acceptDownloads: true });
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.route('**/aula/data.js*', route => route.fulfill({ contentType: 'application/javascript', body: 'window.CURSO=' + JSON.stringify(datos) + ';' }));
  await page.goto(URL_AULA + '#/invitado');
  await page.locator('#nav a[href="#/foro/prensa"]').click();
  await page.waitForSelector('#foroLogin');
  assert.match(await page.locator('h1').innerText(), /Foro de prensa/);
  await page.locator('#foroLogin').click();
  await page.waitForSelector('#lf');
  assert.match(await page.locator('main').innerText(), /Ingresá con tu cuenta para leer los análisis/);
  await registrar(page, 'foro1@ejemplo.test', '4567890', 'Ana');
  await page.goto(URL_AULA + '#/');
  await page.locator('.foro-promo a[href="#/foro/prensa"]').click();
  await page.goto(URL_AULA + '#/foro/prensa');
  await page.waitForSelector('#foroTema');
  assert.match(await page.locator('h1').innerText(), /Foro/);
  await page.locator('#foroTitulo').fill('Unidades en la tabla de exportación');
  await page.locator('#foroTexto').fill('La tabla no aclara US$ por tonelada. Propongo incluir la unidad en el encabezado. <img src=x onerror=alert(1)>');
  await page.locator('#foroTema button').click();
  await page.waitForSelector('.foro-tema');
  assert.equal(await page.locator('#foroTema').count(), 0);
  assert.equal(await page.locator('.foro-tema img').count(), 0);
  assert.match(await page.locator('.foro-tema').innerText(), /Unidades en la tabla/);
  await page.locator('.foro-responder textarea').fill('De acuerdo. También debe indicarse el período enero a abril y la fuente SENACSA.');
  await page.locator('.foro-responder button').click();
  await page.waitForSelector('.foro-respuesta');
  assert.match(await page.locator('.foro-respuesta').innerText(), /período enero a abril/);
  await page.reload();
  await page.waitForSelector('.foro-respuesta');
  assert.equal(await page.locator('.foro-tema').count(), 1);
  const eventos = datos.agenda_base.eventos;
  assert.equal(eventos.length, 10);
  assert.ok(eventos.filter(e => e.tipo === 'clase').every(e => e.enlace.includes('id=6792')));
  assert.ok(eventos.find(e => e.id === 'apertura-s3').todo_el_dia);
  await page.goto(URL_AULA + '#/calendario/clase-5');
  await page.locator('a.btn:has-text("Entrar a la clase")').waitFor();
  assert.match(await page.locator('a.btn:has-text("Entrar a la clase")').getAttribute('href'), /id=6792/);
  await page.goto(URL_AULA + '#/calendario/foro-prensa-s3');
  await page.locator('a.btn:has-text("Participar en el foro")').waitFor();
  assert.match(await page.locator('a.btn:has-text("Participar en el foro")').getAttribute('href'), /#\/foro\/prensa$/);
  await page.goto(URL_AULA + '#/calendario');
  await page.locator('#cIcs').waitFor();
  const delta = (2026 - new Date().getFullYear()) * 12 + (10 - new Date().getMonth());
  for (let i = 0; i < Math.abs(delta); i++) await page.locator(delta > 0 ? '#cNext' : '#cPrev').click();
  assert.match(await page.locator('a.ev:has-text("Sesión 5")').getAttribute('href'), /id=6792/);
  assert.match(await page.locator('a.ev:has-text("Foro de prensa disponible")').getAttribute('href'), /#\/foro\/prensa$/);
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.locator('.cal-lista-movil').isVisible(), true);
  assert.match(await page.locator('.cal-lista-movil').innerText(), /Foro de prensa disponible/);
  assert.match(await page.locator('.cal-lista-movil a:has-text("Ejercicio S3")').getAttribute('href'), /id=6824/);
  await page.setViewportSize({ width: 1280, height: 900 });
  const pending = page.waitForEvent('download');
  await page.locator('#cIcs').click();
  const ical = fs.readFileSync(await (await pending).path(), 'utf8');
  assert.match(ical, /DTSTART;VALUE=DATE:20261124/);
  assert.match(ical, /URL:https:\/\/www\.facet-unc\.edu\.py\/moodle\/mod\/assign\/view\.php\?id=6824/);
  datos.config.agenda.endpoint = 'https://agenda.example.test/api';
  await page.route('https://agenda.example.test/api?action=agenda', route => route.fulfill({ contentType: 'application/json', body: JSON.stringify({ eventos: [{ id: 'tutoria-extra', tipo: 'tutoria', titulo: 'Tutoría confirmada', fecha: '2026-11-25', inicio: '17:00', fin: '18:00', inicio_iso: '2026-11-25T17:00:00-03:00', fin_iso: '2026-11-25T18:00:00-03:00', enlace: 'https://meet.google.com/abc-defg-hij' }] }) }));
  await page.goto(URL_AULA + '?agenda=remote#/calendario');
  await page.locator('#cIcs').waitFor();
  for (let i = 0; i < Math.abs(delta); i++) await page.locator(delta > 0 ? '#cNext' : '#cPrev').click();
  assert.equal(await page.locator('a.ev').count(), 9);
  assert.match(await page.locator('a.ev:has-text("Tutoría confirmada")').getAttribute('href'), /meet\.google\.com/);
  assert.match(await page.locator('a.ev:has-text("Sesión 5")').getAttribute('href'), /id=6792/);
  assert.deepEqual(errors, []);
  await browser.close();
})().catch(e => { console.error(e); process.exitCode = 1; });
